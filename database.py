import os
import uuid
from datetime import datetime

import psycopg
from dotenv import load_dotenv
from psycopg.rows import tuple_row

load_dotenv()
DATABASE_URL = os.getenv("DATABASE_URL")


def get_connection():
    """Open a PostgreSQL connection using DATABASE_URL from .env."""
    if not DATABASE_URL:
        raise RuntimeError(
            "DATABASE_URL is missing. Add your Neon PostgreSQL connection string to .env."
        )
    return psycopg.connect(DATABASE_URL, row_factory=tuple_row)


def init_db():
    """Create the CareRoot conversation tables if they do not already exist."""
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS threads (
                    thread_id TEXT PRIMARY KEY,
                    title TEXT NOT NULL,
                    created_at TEXT NOT NULL
                )
            """)
            cursor.execute("""
                CREATE TABLE IF NOT EXISTS messages (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    thread_id TEXT NOT NULL REFERENCES threads(thread_id) ON DELETE CASCADE,
                    role TEXT NOT NULL,
                    content TEXT NOT NULL,
                    created_at TEXT NOT NULL
                )
            """)
            cursor.execute("""
                CREATE INDEX IF NOT EXISTS idx_messages_thread_id_id
                ON messages (thread_id, id)
            """)


def create_thread(title="New Chat"):
    thread_id = str(uuid.uuid4())
    created_at = datetime.now().isoformat()
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                "INSERT INTO threads (thread_id, title, created_at) VALUES (%s, %s, %s)",
                (thread_id, title, created_at),
            )
    return thread_id


def get_threads():
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute("""
                SELECT thread_id, title, created_at
                FROM threads
                ORDER BY created_at DESC
            """)
            return cursor.fetchall()


def update_thread_title(thread_id, title):
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                "UPDATE threads SET title = %s WHERE thread_id = %s",
                (title, thread_id),
            )


def save_message(thread_id, role, content):
    created_at = datetime.now().isoformat()
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                """INSERT INTO messages (thread_id, role, content, created_at)
                   VALUES (%s, %s, %s, %s)""",
                (thread_id, role, content, created_at),
            )


def get_messages(thread_id):
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                "SELECT role, content FROM messages WHERE thread_id = %s ORDER BY id ASC",
                (thread_id,),
            )
            rows = cursor.fetchall()
    return [{"role": role, "content": content} for role, content in rows]


def delete_thread(thread_id):
    # ON DELETE CASCADE removes the associated messages as well.
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute("DELETE FROM threads WHERE thread_id = %s", (thread_id,))


def get_database_counts():
    """Return row counts for a quick connection/migration check."""
    with get_connection() as conn:
        with conn.cursor() as cursor:
            cursor.execute("SELECT COUNT(*) FROM threads")
            thread_count = cursor.fetchone()[0]
            cursor.execute("SELECT COUNT(*) FROM messages")
            message_count = cursor.fetchone()[0]
    return {"threads": thread_count, "messages": message_count}
